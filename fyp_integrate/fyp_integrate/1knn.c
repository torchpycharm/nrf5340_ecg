double calc_euclidean_sq(const double test_feat[FEAT_DIM], const double train_feat[FEAT_DIM])
{
    double dist_sq = 0.0;
    for (int i = 0; i < FEAT_DIM; i++)
    {
        double diff = test_feat[i] - train_feat[i];
        dist_sq += diff * diff;
    }
    return dist_sq;
}

