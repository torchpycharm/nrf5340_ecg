int load_train_X(const char *filename)
{
    FILE *fp = fopen(filename, "r");
    if (fp == NULL)
    {
        printf("????????????: %s\n", filename);
        return -1;
    }
    for (int i = 0; i < TRAIN_NUM; i++)
    {
        for (int j = 0; j < FEAT_DIM; j++)
        {
            fscanf(fp, "%lf", &train_X[i][j]);
        }
    }
    fclose(fp);
    return 0;
}

